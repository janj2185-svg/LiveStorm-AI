final class LocaleController extends StateNotifier<LocaleCatalog> {
  LocaleController({SharedPreferences? preferences})
    : _preferences = preferences,
      super(const LocaleCatalog('en')) {
    if (preferences != null) {
      _initialization = SynchronousFuture<SharedPreferences>(preferences);
      _read(preferences);
    } else {
      _initialization = SharedPreferences.getInstance().then((value) {
        _preferences = value;
        _read(value);
        return value;
      });
    }
  }

  SharedPreferences? _preferences;
  late final Future<SharedPreferences> _initialization;

  void _read(SharedPreferences preferences) {
    final stored = preferences.getString('locale.code');
    if (stored != null && supportedLocaleCodes.contains(stored)) {
      state = LocaleCatalog(stored);
    }
  }

  Future<void> setCode(String code) async {
    if (!supportedLocaleCodes.contains(code)) {
      return;
    }
    state = LocaleCatalog(code);
    final preferences = _preferences ?? await _initialization;
    state = LocaleCatalog(code);
    await preferences.setString('locale.code', code);
  }
}

final localeControllerProvider =
    StateNotifierProvider<LocaleController, LocaleCatalog>(
      (ref) => LocaleController(),
    );
